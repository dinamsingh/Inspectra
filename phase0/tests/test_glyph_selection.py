import shutil
import sys
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tools"))

import make_coupons_svg as mc                     # noqa: E402
import make_glyph_selection as mgs                # noqa: E402
import validate_selection as vs                   # noqa: E402

from p0.core import dump_json, load_json          # noqa: E402
from p0.render import glyph_shape_class           # noqa: E402

SELECTION = os.path.join(ROOT, "fixtures", "physical", "coupons",
                         "glyph_selection.json")
GLYPH_MAP = os.path.join(ROOT, "fixtures", "physical", "coupons", "glyph_map.json")


def selection():
    return load_json(SELECTION)


def glyph_map():
    return load_json(GLYPH_MAP)


def panels():
    return mgs.load_panels()


def codes(issues, severity="ERROR"):
    return sorted(i["code"] for i in issues if i["severity"] == severity)


def check(sel=None, manifest=None, gmap=None, reference=None, rederive=True):
    sel = sel if sel is not None else selection()
    return vs.validate(sel, manifest, gmap if gmap is not None else glyph_map(),
                       reference, panels() if rederive else None)


def nominal_runs(sel=None, **over):
    sel = sel or selection()
    runs = []
    for g in sel["glyphs"]:
        r = {"run_id": "%s-A-OP1-R1" % g["panel_id"], "panel_id": g["panel_id"],
             "glyph_label": g["glyph_shape"], "nominal_h_mm": g["nominal_h_mm"],
             "glyph_index": 1, "device": "A", "operator": "OP1", "repeat": "R1",
             "safety_class": "SAFE"}
        r.update(over)
        runs.append(r)
    return {"selection_hash": sel["selection_hash"], "runs": runs}


