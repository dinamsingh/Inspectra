"""Tests for the pre-registered panel -> measured-glyph assignment (blocker B5).

These test the **selection and its enforcement only**.  No test asserts a measured
height, none uses physical data, and none changes a criterion.  Several are design
invariants: the allocation is generated by a closed-form rule, so the balance claims
in `docs/B5_GLYPH_SELECTION.md` are asserted here rather than asserted in prose.
"""
from __future__ import annotations

